from config import settings
from services import get_session_manager, get_session_service


class OfflineBootstrapAgent(BaseAgent):
    """Deterministic agent used for offline verification when Gemini API key is absent."""

    greeting: str = (
        "Hello from VideoGuru! Multi-Agent Video Production Pipeline is bootstrapped "
        "and ready. InMemorySessionService and ADK Runner are operational."
    )

    async def _run_async_impl(self, ctx):
        yield Event(
            author=self.name,
            content=types.Content(
                parts=[types.Part.from_text(text=self.greeting)]
            ),
        )


